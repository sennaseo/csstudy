// =============================================================
// 정규화 실습 레슨 데이터
//
// 설계 메모
//   스테이지는 세 종류다.
//   - join      : 이미 쪼개진 두 테이블을 "학번으로 붙이는" 감 잡기 (박스 치기 없음)
//   - atomic    : 한 칸에 값이 여러 개 → 펼치기 (1NF)
//   - decompose : 사용자가 칼럼을 박스로 묶어 테이블을 쪼갠다 (2NF/3NF/BCNF)
//
//   데이터는 일부러 "틀리게 쪼개면 다시 붙였을 때 가짜 행이 튀어나오게" 골랐다.
//   예) BCNF 의 창업전략에 박교수·홍교수 둘이 있는 것 — 이게 없으면 오답도 멀쩡해 보인다.
//   그러니 행을 고칠 땐 normalize.test.ts 를 꼭 돌려볼 것.
// =============================================================

import type { FD, NF, Row } from "../utils/normalize";

type Base = { id: string; emoji: string; title: string; intro: string[] };

export type JoinLesson = Base & {
  kind: "join";
  left: { name: string; cols: string[]; rows: Row[] };
  right: { name: string; cols: string[]; rows: Row[] };
};

export type AtomicLesson = Base & {
  kind: "atomic";
  name: string;
  cols: string[];
  rows: Row[];
  /** 한 칸에 여러 값이 쉼표로 들어간 칼럼 */
  multiCol: string;
  after: string;
};

export type DecomposeLesson = Base & {
  kind: "decompose";
  name: string;
  cols: string[];
  rows: Row[];
  fds: FD[];
  target: NF;
  /** 종속성 보존(③)까지 지켜야 클리어인가. BCNF 는 못 지킬 수 있어 경고만 한다. */
  requirePreserve: boolean;
  hints: string[];
  answer: string[][];
  /** 클리어 뒤에 보여줄 한마디 */
  outro: string;
};

export type Lesson = JoinLesson | AtomicLesson | DecomposeLesson;

